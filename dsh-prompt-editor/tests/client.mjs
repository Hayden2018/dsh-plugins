/**
 * Client-half checks for the Prompt Editor.
 *
 * The Host serves `client.js` as one classic script, so the file must stay
 * self-contained. These checks boot it the way a page does, then drive the
 * registration seam and the inlined select component.
 */

import { readFile } from 'node:fs/promises';

const source = await readFile(new URL('../client.js', import.meta.url), 'utf8');

if (/^\s*(?:import|export)\s/m.test(source)) {
  throw new Error('client.js must not import or export: the host loads it as a classic script');
}
if ((source.match(/__ModuleLoader__\.load\(/g) ?? []).length !== 1) {
  throw new Error('client.js must register exactly one module factory');
}
if (source.includes('Generated by')) {
  throw new Error('client.js is still a generated artifact');
}
for (const marker of [
  'dsh-hselect-trigger',
  'dsh-hselect-option',
  'computeMenuPlacement',
  'ModeSelectBoundary',
]) {
  if (!source.includes(marker)) throw new Error(`client.js is missing the inlined ${marker} code`);
}

// Boot the file as the browser would: the loader queue exists before the script
// runs, and running it registers the factory.
let registration;
globalThis.window = {
  __ModuleLoader__: {
    load(options) {
      registration = options;
    },
  },
};

await import('../client.js');

if (registration === undefined) throw new Error('client.js did not register a module');
if (registration.id !== 'dsh-prompt-editor') {
  throw new Error(`unexpected module id: ${registration.id}`);
}
if (typeof registration.factory !== 'function') throw new Error('registration has no factory');

// The factory asks the loader only for React; a minimal runtime is enough to
// build the component and the plugin object without rendering a page.
const React = {
  createElement: () => null,
  Component: class Component {},
  useCallback: (handler) => handler,
  useEffect: () => {},
  useLayoutEffect: () => {},
  useRef: () => ({ current: null }),
  useState: (value) => [value, () => {}],
};

const plugin = registration.factory((name) => {
  if (name === 'react') return React;
  throw new Error(`unexpected require(${name})`);
});

const expectedInject = ['slots', 'locale', 'configForms', 'remote', 'remote.agentPresets'];
if (JSON.stringify(plugin.inject) !== JSON.stringify(expectedInject)) {
  throw new Error(`unexpected inject list: ${JSON.stringify(plugin.inject)}`);
}
if (typeof plugin.apply !== 'function') throw new Error('plugin has no apply function');

// Drive apply with a recording context: dictionaries and the settings row are
// the two side effects the page cannot show without the host.
const effects = [];
const locales = [];
const slots = [];
const controllerForm = {
  subscribe: () => () => {},
  getSnapshot: () => ({ status: 'ready', writable: true, value: { prompts: {} } }),
  set: async () => true,
};
const ctx = {
  effect(effect, label) {
    effects.push(label);
    effect();
  },
  locale: {
    bind: () => (key) => key,
    register: (namespace, dictionaries) => locales.push({ namespace, dictionaries }),
  },
  configForms: {
    get: () => controllerForm,
    whileServed: (_names, callback) => callback(),
  },
  slots: {
    inject: (_name, callback) => callback(),
    register: (definition, component) => {
      slots.push({ definition, component });
      return () => {};
    },
  },
};

plugin.apply(ctx);

if (locales.length !== 1) throw new Error(`expected one dictionary registration, got ${locales.length}`);
const [locale] = locales;
if (locale.namespace !== 'settings.promptEditor') {
  throw new Error(`unexpected dictionary namespace: ${locale.namespace}`);
}
if (locale.dictionaries.en.nav !== 'Prompt Editor')
  throw new Error('the en dictionary is missing its nav label');
if (locale.dictionaries.zh.nav !== '提示词编辑器')
  throw new Error('the zh dictionary is missing its nav label');
if (Object.keys(locale.dictionaries.en).length !== Object.keys(locale.dictionaries.zh).length) {
  throw new Error('the en and zh dictionaries have different keys');
}

if (slots.length !== 1) throw new Error(`expected one settings row, got ${slots.length}`);
const [slot] = slots;
if (slot.definition.name !== 'plugins.row.config') {
  throw new Error(`unexpected slot name: ${slot.definition.name}`);
}
if (slot.definition.key !== 'dsh-prompt-editor#prompt-editor') {
  throw new Error(`unexpected row key: ${slot.definition.key}`);
}
if (slot.definition.locale !== 'settings.promptEditor') {
  throw new Error(`unexpected row locale: ${slot.definition.locale}`);
}
if (typeof slot.component !== 'function') throw new Error('the settings row is not a component');
if (slot.definition.inject().controller === undefined) {
  throw new Error('the settings row does not receive its controller');
}
if (!effects.includes('prompt-editor: dictionaries') || !effects.includes('prompt-editor: plugin row page')) {
  throw new Error(`missing apply effects: ${effects.join(', ')}`);
}

console.log('prompt-editor client checks ok');
